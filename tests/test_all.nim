## Main test runner -- `nimble test` builds and runs THIS file.
##
## It imports every `tests/test_*.nim` except the files named in
## `ExcludedTests` below, and it prints a coverage manifest so that a test file
## which is on disk but not in the run can never again be invisible.
##
## WHY THIS FILE LOOKS LIKE THIS (2026-09-06)
## ------------------------------------------
## It used to be a hand-written list of 112 `import ./test_x` lines, and it
## reported green over a failing run.  Two stacked defects:
##
##   1. 112 of the 224 `tests/test_*.nim` files were imported.  The other 112,
##      holding 2,921 declared tests, were never compiled and never run.  There
##      was nothing to notice: a test file that nobody imports produces no
##      output at all.
##
##   2. The `[Summary]` line is unittest2's own counter.  83 of the 112
##      imported modules used `unittest2`; the other 29 used stdlib
##      `std/unittest`, a separate framework with a separate reporter and a
##      separate counter.  unittest2 counted its 2,177 and was structurally
##      blind to the other 726 -- including all 17 failures that run had.
##      2,177 + 726 = 2,903, and the printed line said
##      `2177 tests run: 2177 OK, 0 FAILED`.
##
## The fixes, in the same order:
##
##   1. The import list is generated by `importTestModules` from the explicit
##      `IncludedTests` array below, and a compile-time guard cross-checks that
##      array plus `ExcludedTests` against what is actually in `tests/`.  Drop a
##      new `test_*.nim` in and forget to list it and the BUILD FAILS naming the
##      file -- it cannot go quiet.
##
##   2. Every test module in `tests/` now uses `unittest2`.  75 files that used
##      stdlib `std/unittest` were converted.  One framework means one reporter
##      and one counter, so `[Summary]` is complete by construction rather than
##      by anyone remembering to keep two numbers in sync.
##
## Anything that genuinely cannot be in the run is named, with its reason, in
## `ExcludedTests`, and `[Coverage]` prints that list after every run.
##
## `nimble test` == `nim c -r tests/test_all.nim`.  Individual files still
## compile and run standalone; `./run-all-tests.sh` does that for all of them
## (slow: one nim compile per file).

