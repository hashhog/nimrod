## Every tests/test_*.nim actually present, read at COMPILE time.  This is the
## denominator the guard below and the [Coverage] line are measured against.
const OnDiskTests = discoverTestModules(TestsDir)

static:
  ## Completeness guard.  Fails the BUILD -- not a runtime warning -- if a
  ## tests/test_*.nim exists that is neither imported nor explicitly excluded,
  ## or if either list names a file that no longer exists.
  doAssert OnDiskTests.len > 100,
    "test discovery found only " & $OnDiskTests.len & " files in " & TestsDir &
    " -- refusing to build an aggregate that cannot see the test suite"

  var excludedNames: seq[string]
  for e in ExcludedTests: excludedNames.add e.module

  var unaccounted: seq[string]
  for m in OnDiskTests:
    if m notin IncludedTests and m notin excludedNames: unaccounted.add m
  doAssert unaccounted.len == 0,
    "tests/test_all.nim accounts for neither importing nor excluding: " &
    unaccounted.join(", ") &
    " -- add each to IncludedTests, or to ExcludedTests with a reason"

  var ghosts: seq[string]
  for m in IncludedTests:
    if m notin OnDiskTests: ghosts.add m
  for m in excludedNames:
    if m notin OnDiskTests: ghosts.add m
  doAssert ghosts.len == 0,
    "tests/test_all.nim lists files that are not on disk: " & ghosts.join(", ")

importTestModules(TestsDir, IncludedTests)

when isMainModule:
  covOnDisk = OnDiskTests.len
  covIncluded = IncludedTests.len
  covExcluded = ExcludedTests
  echo "Running all tests (", covIncluded, " test modules, ",
       ExcludedTests.len, " excluded -- see [Coverage] below the summary)..."
